import { NextRequest, NextResponse } from "next/server";
import mongoose from "mongoose";

import { authorizeHotel } from "@/lib/auth/authorize-hotel";
import { RoomAsset } from "@/models/Room-Asset";
import { Room } from "@/models/Room";

type RouteContext = {
  params: Promise<{
    hotelId: string;
    roomId: string;
  }>;
};

// GET: List assets
export async function GET(request: NextRequest, context: RouteContext) {
  try {
    const { hotelId, roomId } = await context.params;

    const auth = await authorizeHotel(hotelId);

    if (!auth.success) {
      return NextResponse.json(
        { message: auth.message },
        { status: auth.status },
      );
    }

    if (!mongoose.isValidObjectId(roomId)) {
      return NextResponse.json({ message: "Invalid roomId." }, { status: 400 });
    }

    const room = await Room.exists({
      _id: roomId,
      hotelId: auth.hotelId,
    });

    if (!room) {
      return NextResponse.json({ message: "Room not found." }, { status: 404 });
    }

    const assets = await RoomAsset.find({
      hotelId: auth.hotelId,
      roomId,
    })
      .sort({ sortOrder: 1 })
      .lean();

    return NextResponse.json({
      data: assets,
    });
  } catch (error) {
    console.error("GET ROOM ASSETS ERROR:", error);

    return NextResponse.json(
      { message: "Internal server error." },
      { status: 500 },
    );
  }
}

// POST: Create asset metadata
export async function POST(request: NextRequest, context: RouteContext) {
  try {
    const { hotelId, roomId } = await context.params;

    const auth = await authorizeHotel(hotelId);

    if (!auth.success) {
      return NextResponse.json(
        { message: auth.message },
        { status: auth.status },
      );
    }

    if (!mongoose.isValidObjectId(roomId)) {
      return NextResponse.json({ message: "Invalid roomId." }, { status: 400 });
    }

    const room = await Room.exists({
      _id: roomId,
      hotelId: auth.hotelId,
    });

    if (!room) {
      return NextResponse.json({ message: "Room not found." }, { status: 404 });
    }

    const body = await request.json();

    const {
      resourceType,
      category,
      publicId,
      secureUrl,
      format,
      mimeType,
      size,
      width,
      height,
      duration,
      altText,
      caption,
      isPrimary,
      sortOrder,
    } = body;

    if (!resourceType || !publicId || !secureUrl || !mimeType) {
      return NextResponse.json(
        { message: "Missing required asset fields." },
        { status: 400 },
      );
    }

    if (!["IMAGE", "VIDEO", "DOCUMENT"].includes(resourceType)) {
      return NextResponse.json(
        { message: "Invalid resource type." },
        { status: 400 },
      );
    }

    // IMPORTANT:
    // In production, verify the uploaded asset with Cloudinary
    // using publicId before saving metadata.
    //
    // Also verify:
    // - Cloudinary folder belongs to this hotel and room
    // - resource type matches
    // - file size and MIME type are allowed
    // - secureUrl is generated by Cloudinary

    if (typeof secureUrl !== "string" || !secureUrl.startsWith("https://")) {
      return NextResponse.json(
        { message: "Invalid asset URL." },
        { status: 400 },
      );
    }

    if (typeof size !== "number" || !Number.isFinite(size) || size < 0) {
      return NextResponse.json(
        { message: "Invalid asset size." },
        { status: 400 },
      );
    }

    // Unset the previous primary asset first.
    if (isPrimary === true) {
      await RoomAsset.updateMany(
        {
          roomId,
          resourceType,
          isPrimary: true,
        },
        {
          $set: {
            isPrimary: false,
          },
        },
      );
    }

    const asset = await RoomAsset.create({
      hotelId: auth.hotelId,
      roomId,
      resourceType,
      category,
      publicId,
      secureUrl,
      format,
      mimeType,
      size,
      width,
      height,
      duration,
      altText,
      caption,
      isPrimary: isPrimary === true,
      sortOrder: sortOrder ?? 0,
      uploadedBy: auth.userId,
    });

    return NextResponse.json(
      {
        message: "Asset created successfully.",
        data: asset,
      },
      { status: 201 },
    );
  } catch (error) {
    if ((error as { code?: number }).code === 11000) {
      return NextResponse.json(
        { message: "Primary asset already exists." },
        { status: 409 },
      );
    }

    console.error("CREATE ROOM ASSET ERROR:", error);

    return NextResponse.json(
      { message: "Internal server error." },
      { status: 500 },
    );
  }
}
